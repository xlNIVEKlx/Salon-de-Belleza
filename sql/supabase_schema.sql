-- ── SEDES ─────────────────────────────────────────────────
-- Todos pueden leer sedes activas; solo admin puede modificar
CREATE POLICY "sedes_lectura_todos"
    ON sedes FOR SELECT
    USING (true);

CREATE POLICY "sedes_admin_total"
    ON sedes FOR ALL
    USING (is_admin());

-- ── PERFILES ──────────────────────────────────────────────
-- Cada usuario ve su propio perfil; admin ve todos
CREATE POLICY "perfiles_lectura"
    ON perfiles FOR SELECT
    USING (id = auth.uid() OR is_admin());

CREATE POLICY "perfiles_update_propio"
    ON perfiles FOR UPDATE
    USING (id = auth.uid() OR is_admin());

-- ── CATÁLOGO ──────────────────────────────────────────────
-- Todos pueden leer; solo admin puede gestionar
CREATE POLICY "catalogo_lectura_todos"
    ON catalogo_servicios FOR SELECT
    USING (true);

CREATE POLICY "catalogo_admin_total"
    ON catalogo_servicios FOR ALL
    USING (is_admin());

-- ── JORNADAS ──────────────────────────────────────────────
-- Cada trabajadora ve sus propias jornadas; admin ve todas
CREATE POLICY "jornadas_lectura"
    ON jornadas FOR SELECT
    USING (usuario_id = auth.uid() OR is_admin());

-- Solo puede insertar jornadas propias
CREATE POLICY "jornadas_insertar_propia"
    ON jornadas FOR INSERT
    WITH CHECK (usuario_id = auth.uid());

-- Solo puede actualizar sus jornadas (o admin)
CREATE POLICY "jornadas_actualizar"
    ON jornadas FOR UPDATE
    USING (usuario_id = auth.uid() OR is_admin());

-- ── SERVICIOS REALIZADOS ──────────────────────────────────
-- Ver solo servicios de jornadas propias (o admin ve todo)
CREATE POLICY "sr_lectura"
    ON servicios_realizados FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM jornadas j
            WHERE j.id = jornada_id
              AND (j.usuario_id = auth.uid() OR is_admin())
        )
    );

-- Insertar solo en jornada propia y abierta
CREATE POLICY "sr_insertar_jornada_propia"
    ON servicios_realizados FOR INSERT
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM jornadas j
            WHERE j.id = jornada_id
              AND j.usuario_id = auth.uid()
              AND j.estado = 'ABIERTA'
        )
    );


-- ────────────────────────────────────────────────────────────
-- SUPABASE REALTIME
-- Habilitar la publicación en tiempo real para las tablas clave
-- ────────────────────────────────────────────────────────────

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND tablename = 'servicios_realizados'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE servicios_realizados;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND tablename = 'jornadas'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE jornadas;
    END IF;
END $$;


